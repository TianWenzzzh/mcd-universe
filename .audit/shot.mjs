import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { chromium } = require("playwright-core");
const base = 'http://127.0.0.1:8811/demo/';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
const p = await ctx.newPage();
p.on('console', m => { if (m.type() === 'error') console.log('CONSOLE ERR', m.text()); });
await p.goto(base, { waitUntil: 'load' });
await p.waitForTimeout(1500);
await p.screenshot({ path: '.audit/d1-onboard.png' });
await p.keyboard.press('Escape').catch(()=>{});
await p.waitForTimeout(7000);
await p.screenshot({ path: '.audit/d2-map.png' });
const ctx2 = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
const p2 = await ctx2.newPage();
await p2.goto(base, { waitUntil: 'load' });
await p2.waitForTimeout(1500);
await p2.screenshot({ path: '.audit/m1-onboard.png' });
await b.close();
